#!/usr/bin/env bash
set -euo pipefail

SESSION_NAME=${SESSION_NAME:-alfworld_fcsr_gigpo_smoke}
PROJECT_ROOT=${PROJECT_ROOT:-/root/data/zh/gigpo+fcsr_verl}
SCRIPT_PATH="$PROJECT_ROOT/examples/fcsr_trainer/run_alfworld_fcsr_gigpo_qwen25_1p5b.sh"

if [[ "${IN_TMUX_RUNNER:-0}" != "1" ]]; then
  if tmux has-session -t "$SESSION_NAME" 2>/dev/null; then
    echo "tmux session already exists: $SESSION_NAME"
    echo "Attach with: tmux attach -t $SESSION_NAME"
    exit 1
  fi

  tmux new-session -d -s "$SESSION_NAME" "cd '$PROJECT_ROOT' && env IN_TMUX_RUNNER=1 SESSION_NAME='$SESSION_NAME' PROJECT_ROOT='$PROJECT_ROOT' TS='${TS:-}' RUN_NAME='${RUN_NAME:-}' CKPT_DIR='${CKPT_DIR:-}' LOG_DIR='${LOG_DIR:-}' LOG_FILE='${LOG_FILE:-}' TOTAL_EPOCHS='${TOTAL_EPOCHS:-}' TRAIN_DATA_SIZE='${TRAIN_DATA_SIZE:-}' VAL_DATA_SIZE='${VAL_DATA_SIZE:-}' VAL_BATCH_SIZE='${VAL_BATCH_SIZE:-}' GROUP_SIZE='${GROUP_SIZE:-}' ALFWORLD_MAX_STEPS='${ALFWORLD_MAX_STEPS:-}' MAX_RESPONSE_LENGTH='${MAX_RESPONSE_LENGTH:-}' ROLLOUT_TEMPERATURE='${ROLLOUT_TEMPERATURE:-}' VAL_TEMPERATURE='${VAL_TEMPERATURE:-}' REWARD_CLIP_MIN='${REWARD_CLIP_MIN:-}' REWARD_CLIP_MAX='${REWARD_CLIP_MAX:-}' KL_LOSS_COEF='${KL_LOSS_COEF:-}' CLIP_RATIO_HIGH='${CLIP_RATIO_HIGH:-}' CLIP_RATIO_LOW='${CLIP_RATIO_LOW:-}' PPO_MINI_BATCH_SIZE='${PPO_MINI_BATCH_SIZE:-}' ACTOR_PPO_MICRO_BATCH_SIZE_PER_GPU='${ACTOR_PPO_MICRO_BATCH_SIZE_PER_GPU:-}' PPO_MICRO_BATCH_SIZE_PER_GPU='${PPO_MICRO_BATCH_SIZE_PER_GPU:-}' ALFWORLD_PROMPT_STYLE='${ALFWORLD_PROMPT_STYLE:-}' ALFWORLD_ALLOW_BARE_ADMISSIBLE='${ALFWORLD_ALLOW_BARE_ADMISSIBLE:-}' ALFWORLD_ACTION_GATE_ENABLED='${ALFWORLD_ACTION_GATE_ENABLED:-}' WANDB_MODE='${WANDB_MODE:-}' bash '$0'"
  echo "Started tmux session: $SESSION_NAME"
  echo "Attach: tmux attach -t $SESSION_NAME"
  echo "Detach inside tmux: Ctrl-b d"
  exit 0
fi

cd "$PROJECT_ROOT"

TS=${TS:-$(date +%Y%m%d_%H%M%S)}
export TOTAL_EPOCHS=${TOTAL_EPOCHS:-300}
export RUN_NAME=${RUN_NAME:-alfworld_fcsr_gigpo_qwen25_1p5b_from0_to300_${TS}}
export CKPT_DIR=${CKPT_DIR:-$PROJECT_ROOT/checkpoints/verl_agent_alfworld/$RUN_NAME}
export LOG_DIR=${LOG_DIR:-$PROJECT_ROOT/outputs/alfworld_fcsr_gigpo_runs/$RUN_NAME}
export LOG_FILE=${LOG_FILE:-$LOG_DIR/train.from0_to300.log}

export MODEL_PATH=${MODEL_PATH:-/root/data/zh/huggingface/Qwen2.5-1.5B-Instruct}
export ALFWORLD_DATA=${ALFWORLD_DATA:-/root/data/.cache/alfworld}
export DATA_DIR=${DATA_DIR:-/root/data/verl-agent/text}
export TRAIN_FILE=${TRAIN_FILE:-$DATA_DIR/train.parquet}
export VAL_FILE=${VAL_FILE:-$DATA_DIR/test.parquet}
export PREPARE_ALFWORLD_DATA=${PREPARE_ALFWORLD_DATA:-0}
export CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES:-0,1,2,3}
export N_GPUS_PER_NODE=${N_GPUS_PER_NODE:-4}
export TP_SIZE=${TP_SIZE:-2}
export TRAIN_DATA_SIZE=${TRAIN_DATA_SIZE:-16}
export VAL_DATA_SIZE=${VAL_DATA_SIZE:-128}
export VAL_BATCH_SIZE=${VAL_BATCH_SIZE:-128}
export PREP_VAL_DATA_SIZE=${PREP_VAL_DATA_SIZE:-$VAL_DATA_SIZE}
export GROUP_SIZE=${GROUP_SIZE:-8}
export NUM_CPUS_PER_ENV_WORKER=${NUM_CPUS_PER_ENV_WORKER:-0.1}
export ALFWORLD_MAX_STEPS=${ALFWORLD_MAX_STEPS:-30}
export SAVE_FREQ=${SAVE_FREQ:-20}
export TEST_FREQ=${TEST_FREQ:-10}
export VAL_BEFORE_TRAIN=${VAL_BEFORE_TRAIN:-True}
export MONITOR_KL_ESTIMATORS=${MONITOR_KL_ESTIMATORS:-true}
export KL_MONITOR_INTERVAL=${KL_MONITOR_INTERVAL:-1}
export HYDRA_FULL_ERROR=${HYDRA_FULL_ERROR:-1}
export VLLM_ATTENTION_BACKEND=${VLLM_ATTENTION_BACKEND:-XFORMERS}
export WANDB_MODE=${WANDB_MODE:-offline}
unset PYTORCH_CUDA_ALLOC_CONF
export PPO_MINI_BATCH_SIZE=${PPO_MINI_BATCH_SIZE:-256}
export ACTOR_PPO_MICRO_BATCH_SIZE_PER_GPU=${ACTOR_PPO_MICRO_BATCH_SIZE_PER_GPU:-${PPO_MICRO_BATCH_SIZE_PER_GPU:-32}}
export ROLLOUT_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU=${ROLLOUT_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU:-16}
export REF_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU=${REF_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU:-16}
export ROLLOUT_GPU_MEMORY_UTILIZATION=${ROLLOUT_GPU_MEMORY_UTILIZATION:-0.55}
export MAX_RESPONSE_LENGTH=${MAX_RESPONSE_LENGTH:-128}
export ROLLOUT_TEMPERATURE=${ROLLOUT_TEMPERATURE:-0.4}
export VAL_TEMPERATURE=${VAL_TEMPERATURE:-0.4}
export REWARD_CLIP_MIN=${REWARD_CLIP_MIN:--0.2}
export REWARD_CLIP_MAX=${REWARD_CLIP_MAX:-1.0}
export ALFWORLD_ACTION_GATE_ENABLED=${ALFWORLD_ACTION_GATE_ENABLED:-true}
export ALFWORLD_PROMPT_STYLE=${ALFWORLD_PROMPT_STYLE:-action_only_bare}
export ALFWORLD_ALLOW_BARE_ADMISSIBLE=${ALFWORLD_ALLOW_BARE_ADMISSIBLE:-true}
export KL_LOSS_COEF=${KL_LOSS_COEF:-0.02}
export CLIP_RATIO_LOW=${CLIP_RATIO_LOW:-0.2}
export CLIP_RATIO_HIGH=${CLIP_RATIO_HIGH:-0.2}
export ENTROPY_COEFF=${ENTROPY_COEFF:-0.0005}
export ACTOR_INVALID_ACTION_PENALTY_COEF=${ACTOR_INVALID_ACTION_PENALTY_COEF:-0.1}
export OMEGA_ENV=${OMEGA_ENV:-0.7}
export OMEGA_FCSR=${OMEGA_FCSR:-0.2}
export LAMBDA_FALLBACK=${LAMBDA_FALLBACK:-0.02}
export FCSR_NORM_TYPE=${FCSR_NORM_TYPE:-none}
export DENSE_REWARD_WEIGHT=${DENSE_REWARD_WEIGHT:-0.25}
export HBRR_REWARD_WEIGHT=${HBRR_REWARD_WEIGHT:-0.10}
export PENALTY_INVALID=${PENALTY_INVALID:-0.2}
export PENALTY_NOOP=${PENALTY_NOOP:-0.1}
export PENALTY_REPEAT=${PENALTY_REPEAT:-0.1}
export ALFWORLD_GATE_INVALID_CLAMP=${ALFWORLD_GATE_INVALID_CLAMP:--0.2}
export ALFWORLD_GATE_NOOP_REPEAT_CLAMP=${ALFWORLD_GATE_NOOP_REPEAT_CLAMP:--0.1}
export ALFWORLD_DEBUG_DUMP=${ALFWORLD_DEBUG_DUMP:-true}
export ALFWORLD_DEBUG_DUMP_DIR=$LOG_DIR/alfworld_debug_samples
export ALFWORLD_DEBUG_DUMP_INTERVAL=${ALFWORLD_DEBUG_DUMP_INTERVAL:-1}
export ALFWORLD_DEBUG_DUMP_MAX_SAMPLES=${ALFWORLD_DEBUG_DUMP_MAX_SAMPLES:-20}

unset RESUME_STEP
unset RESUME_CKPT
unset RESUME_FROM_PATH
unset WANDB_RUN_ID
unset WANDB_RESUME

if [[ "${PYTORCH_CUDA_ALLOC_CONF:-}" == *"expandable_segments:True"* ]]; then
  echo "Unsetting PYTORCH_CUDA_ALLOC_CONF=$PYTORCH_CUDA_ALLOC_CONF because vLLM CuMemAllocator is incompatible with expandable_segments:True" >&2
  unset PYTORCH_CUDA_ALLOC_CONF
fi

mkdir -p "$LOG_DIR" "$CKPT_DIR"

{
  echo "RUN_NAME=$RUN_NAME"
  echo "CKPT_DIR=$CKPT_DIR"
  echo "LOG_FILE=$LOG_FILE"
  echo "MODEL_PATH=$MODEL_PATH"
  echo "ALFWORLD_DATA=$ALFWORLD_DATA"
  echo "DATA_DIR=$DATA_DIR"
  echo "TRAIN_FILE=$TRAIN_FILE"
  echo "VAL_FILE=$VAL_FILE"
  echo "PREPARE_ALFWORLD_DATA=$PREPARE_ALFWORLD_DATA"
  echo "CUDA_VISIBLE_DEVICES=$CUDA_VISIBLE_DEVICES"
  echo "TRAIN_DATA_SIZE=$TRAIN_DATA_SIZE VAL_DATA_SIZE=$VAL_DATA_SIZE VAL_BATCH_SIZE=$VAL_BATCH_SIZE GROUP_SIZE=$GROUP_SIZE"
  echo "N_GPUS_PER_NODE=$N_GPUS_PER_NODE TP_SIZE=$TP_SIZE"
  echo "ALFWORLD_MAX_STEPS=$ALFWORLD_MAX_STEPS TOTAL_EPOCHS=$TOTAL_EPOCHS"
  echo "PPO_MINI_BATCH_SIZE=$PPO_MINI_BATCH_SIZE ACTOR_PPO_MICRO_BATCH_SIZE_PER_GPU=$ACTOR_PPO_MICRO_BATCH_SIZE_PER_GPU"
  echo "ROLLOUT_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU=$ROLLOUT_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU REF_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU=$REF_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU"
  echo "ROLLOUT_GPU_MEMORY_UTILIZATION=$ROLLOUT_GPU_MEMORY_UTILIZATION"
  echo "MAX_RESPONSE_LENGTH=$MAX_RESPONSE_LENGTH ROLLOUT_TEMPERATURE=$ROLLOUT_TEMPERATURE VAL_TEMPERATURE=$VAL_TEMPERATURE"
  echo "KL_LOSS_COEF=$KL_LOSS_COEF CLIP_RATIO_LOW=$CLIP_RATIO_LOW CLIP_RATIO_HIGH=$CLIP_RATIO_HIGH ENTROPY_COEFF=$ENTROPY_COEFF"
  echo "OMEGA_ENV=$OMEGA_ENV OMEGA_FCSR=$OMEGA_FCSR LAMBDA_FALLBACK=$LAMBDA_FALLBACK FCSR_NORM_TYPE=$FCSR_NORM_TYPE"
  echo "DENSE_REWARD_WEIGHT=$DENSE_REWARD_WEIGHT HBRR_REWARD_WEIGHT=$HBRR_REWARD_WEIGHT PENALTY_INVALID=$PENALTY_INVALID PENALTY_NOOP=$PENALTY_NOOP PENALTY_REPEAT=$PENALTY_REPEAT"
  echo "REWARD_CLIP_MIN=$REWARD_CLIP_MIN REWARD_CLIP_MAX=$REWARD_CLIP_MAX ALFWORLD_ACTION_GATE_ENABLED=$ALFWORLD_ACTION_GATE_ENABLED"
  echo "ALFWORLD_PROMPT_STYLE=$ALFWORLD_PROMPT_STYLE ALFWORLD_ALLOW_BARE_ADMISSIBLE=$ALFWORLD_ALLOW_BARE_ADMISSIBLE ALFWORLD_GATE_INVALID_CLAMP=$ALFWORLD_GATE_INVALID_CLAMP ALFWORLD_GATE_NOOP_REPEAT_CLAMP=$ALFWORLD_GATE_NOOP_REPEAT_CLAMP"
  echo "ALFWORLD_DEBUG_DUMP=$ALFWORLD_DEBUG_DUMP ALFWORLD_DEBUG_DUMP_DIR=$ALFWORLD_DEBUG_DUMP_DIR ALFWORLD_DEBUG_DUMP_INTERVAL=$ALFWORLD_DEBUG_DUMP_INTERVAL ALFWORLD_DEBUG_DUMP_MAX_SAMPLES=$ALFWORLD_DEBUG_DUMP_MAX_SAMPLES"
  echo "PYTORCH_CUDA_ALLOC_CONF=${PYTORCH_CUDA_ALLOC_CONF:-<unset>}"
  echo "reward_method=fcsr_lite"
  echo "algorithm.adv_estimator=fcsr_gigpo"
} | tee -a "$LOG_FILE"

bash "$SCRIPT_PATH" vllm fcsr 2>&1 | tee -a "$LOG_FILE"
